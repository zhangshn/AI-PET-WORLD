import type { MapPlacement } from "./home-map-state-schema"

// Preserve the existing audit string format; this is not a cryptographic hash.
export function fingerprintMapPlacements(placements: MapPlacement[]): string {
  return placements
    .map((placement) =>
      [
        placement.id,
        placement.layer,
        String(placement.x),
        String(placement.y),
        String(placement.alpha),
        placement.tags.slice().sort().join("+"),
      ].join(":")
    )
    .sort()
    .join("|")
}
