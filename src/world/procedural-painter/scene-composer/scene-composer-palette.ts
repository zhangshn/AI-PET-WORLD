import type { SceneComposerBiome, ScenePalette } from "./scene-composer-schema";

export function buildScenePalette(
  biome: SceneComposerBiome,
  moisture: number
): ScenePalette {
  const dry = moisture <= 35;
  const wet = moisture >= 72;

  if (biome === "desert") {
    return {
      bg: "#17231f",
      grassA: dry ? "#8a7c47" : wet ? "#697849" : "#817e40",
      grassB: dry ? "#9b884c" : wet ? "#748858" : "#8a8848",
      grassC: dry ? "#71683b" : wet ? "#52663e" : "#706f3d",
      grassDark: dry ? "#625833" : wet ? "#3f5132" : "#5a6135",
      grassLight: dry ? "#b8a45e" : wet ? "#96a96a" : "#b0a85c",
      soilA: dry ? "#a9743b" : wet ? "#66593a" : "#84683d",
      soilB: dry ? "#b88243" : wet ? "#746440" : "#927344",
      soilDark: dry ? "#704e2d" : wet ? "#46402d" : "#5d4a30",
      soilLight: dry ? "#c99b5a" : wet ? "#8b7f55" : "#a98c58",
      pressedGrass: dry ? "#766f3e" : wet ? "#4b6340" : "#667141",
      wornGrass: dry ? "#817442" : wet ? "#5d6b43" : "#756f40",
      recoveryGrass: dry ? "#a8ad66" : wet ? "#83a36c" : "#9fb05f",
      ecologyBlend: wet ? "#577457" : dry ? "#8b834c" : "#788451",
      pathA: dry ? "#cf9346" : wet ? "#9c7c3f" : "#b58a42",
      pathB: dry ? "#dda34f" : wet ? "#aa8848" : "#c2964a",
      pathDark: "#8a6334",
      pathLight: "#e3bd68",
      shadow: "#1b2117",
      trunkDark: "#6b4b2b",
      trunk: "#9b7445",
      trunkLight: "#c79a5e",
      leafDark: dry ? "#565532" : wet ? "#465431" : "#4f5c30",
      leaf: dry ? "#8e8b4c" : wet ? "#768c52" : "#88904e",
      leafLight: dry ? "#bdb468" : wet ? "#9eae6b" : "#bdbb6b",
      leafUnder: dry ? "#3f3e25" : wet ? "#344229" : "#384020",
      bushDark: dry ? "#5c5c35" : wet ? "#435631" : "#4e552f",
      bush: dry ? "#88894d" : wet ? "#6f8b54" : "#7d8849",
      bushLight: dry ? "#bdbb68" : wet ? "#95aa69" : "#b7b85f",
      stone: "#6a6245",
      stoneLight: "#9a8f62",
      flower: "#e9d783",
      mushroomCap: dry ? "#9d6a4f" : "#b68168",
      mushroomStem: dry ? "#c7b27b" : "#d5cda2",
      insectSignal: wet ? "#d8f0a6" : "#f0d77f",
      actorDark: "#604131",
      actor: "#a87b54",
    };
  }

  if (biome === "oasis") {
    return {
      bg: "#17231f",
      grassA: dry ? "#5f814e" : wet ? "#246f52" : "#3f8559",
      grassB: dry ? "#6d9258" : wet ? "#2e8060" : "#479466",
      grassC: dry ? "#466b42" : wet ? "#1c5c49" : "#2f6d4d",
      grassDark: dry ? "#36543a" : wet ? "#104634" : "#25513a",
      grassLight: dry ? "#9fbf7f" : wet ? "#78b894" : "#87d69a",
      soilA: dry ? "#82714d" : wet ? "#4d5c42" : "#666945",
      soilB: dry ? "#927f56" : wet ? "#596a4b" : "#74764e",
      soilDark: dry ? "#5f553d" : wet ? "#344333" : "#48503a",
      soilLight: dry ? "#ad9d6a" : wet ? "#7f8f66" : "#90945f",
      pressedGrass: dry ? "#55774b" : wet ? "#1f6049" : "#367351",
      wornGrass: dry ? "#667c4d" : wet ? "#3f654d" : "#4e7350",
      recoveryGrass: dry ? "#88b879" : wet ? "#72c394" : "#83cc91",
      ecologyBlend: wet ? "#3d8d73" : dry ? "#769263" : "#5e9b72",
      pathA: dry ? "#a88c50" : wet ? "#5b6844" : "#7d7748",
      pathB: dry ? "#b99b5b" : wet ? "#69774d" : "#8b8551",
      pathDark: "#4f5b36",
      pathLight: "#b9c878",
      shadow: "#102019",
      trunkDark: "#604028",
      trunk: "#936139",
      trunkLight: "#bf8953",
      leafDark: dry ? "#37684c" : wet ? "#0e5c45" : "#1c634e",
      leaf: dry ? "#6f9d70" : wet ? "#2f946e" : "#4b9d77",
      leafLight: dry ? "#a1c48d" : wet ? "#7fc79d" : "#8ed0a0",
      leafUnder: dry ? "#315641" : wet ? "#0d4034" : "#16483b",
      bushDark: dry ? "#286547" : wet ? "#0f543d" : "#1a6b4f",
      bush: dry ? "#63a06f" : wet ? "#359368" : "#4fb77e",
      bushLight: dry ? "#a3cf8c" : wet ? "#7fc79d" : "#9deab4",
      stone: "#48665d",
      stoneLight: "#78a090",
      flower: "#f48be5",
      mushroomCap: dry ? "#a87072" : "#d58aa0",
      mushroomStem: dry ? "#c9bf92" : "#e0dcbc",
      insectSignal: wet ? "#b9ffd2" : "#f0e58b",
      actorDark: "#426a5c",
      actor: "#95c7b0",
    };
  }

  return {
    bg: "#17231f",
    grassA: dry ? "#667e43" : wet ? "#1f7336" : "#3f7d3c",
    grassB: dry ? "#758d4e" : wet ? "#2a8541" : "#4f8d43",
    grassC: dry ? "#4d6338" : wet ? "#185a2d" : "#336936",
    grassDark: dry ? "#38482b" : wet ? "#0d3f1f" : "#28572c",
    grassLight: dry ? "#9daf62" : wet ? "#67a95a" : "#7fc360",
    soilA: dry ? "#98703e" : wet ? "#5f5537" : "#735b35",
    soilB: dry ? "#a97d45" : wet ? "#6e613f" : "#80653a",
    soilDark: dry ? "#674b2f" : wet ? "#3f3928" : "#4f3e2a",
    soilLight: dry ? "#bd9359" : wet ? "#837757" : "#997f51",
    pressedGrass: dry ? "#5f7440" : wet ? "#216438" : "#3a7138",
    wornGrass: dry ? "#6d7541" : wet ? "#466742" : "#536d3e",
    recoveryGrass: dry ? "#8faa58" : wet ? "#5fb866" : "#74bd5d",
    ecologyBlend: dry ? "#788850" : wet ? "#3b8a55" : "#5f934c",
    pathA: dry ? "#c09243" : wet ? "#956f32" : "#a57934",
    pathB: dry ? "#ce9d4b" : wet ? "#a47d3a" : "#b3843b",
    pathDark: "#805d2f",
    pathLight: "#d5a75b",
    shadow: "#111b15",
    trunkDark: "#5a351f",
    trunk: "#8a5a31",
    trunkLight: "#b87a3a",
    leafDark: dry ? "#354c2b" : wet ? "#0c4825" : "#154526",
    leaf: dry ? "#668a45" : wet ? "#2f8a3d" : "#3f873d",
    leafLight: dry ? "#9fb563" : wet ? "#68b85a" : "#7ec35c",
    leafUnder: dry ? "#263b25" : wet ? "#0a321b" : "#10351e",
    bushDark: dry ? "#3c5c31" : wet ? "#0e4c26" : "#17612f",
    bush: dry ? "#6f984a" : wet ? "#2c8941" : "#3da248",
    bushLight: dry ? "#a7bd65" : wet ? "#69b85b" : "#8fdb65",
    stone: "#536354",
    stoneLight: "#81927d",
    flower: biome === "grassland" ? "#f5f0a8" : "#e8f0db",
    mushroomCap: dry ? "#9a6650" : wet ? "#bd7785" : "#ad735f",
    mushroomStem: dry ? "#c2af78" : wet ? "#d8d1a9" : "#d0c08f",
    insectSignal: wet ? "#bdf7a0" : biome === "grassland" ? "#fff18c" : "#d9ed8f",
    actorDark: "#6c4930",
    actor: "#b89260",
  };
}
