export function getRelationshipStructureContentDetail(
  relationId: ZiweiRelationshipStructureId
): ZiweiRelationshipStructureContentDetail | undefined {
  return ZIWEI_RELATIONSHIP_STRUCTURE_DETAILS.find((detail) => detail.relationId === relationId)
}

