const visualUnitMaterials = await Promise.all(
  compositeBuild.manifest.visualUnitSlots.map(async (slot, index) => {
    const imageWidth = Math.max(1, Math.ceil(slot.bounds.width))
    const imageHeight = Math.max(1, Math.ceil(slot.bounds.height))
    const imagePath = join(materialImageDir, `${slot.slotId}.png`)
    const materialBytes = await sharp({
      create: {
        width: imageWidth,
        height: imageHeight,
        channels: 4,
        background: {
          r: 64 + ((index * 31) % 128),
          g: 96 + ((index * 17) % 128),
          b: 80 + ((index * 23) % 128),
          alpha: 1,
        },
      },
    })
      .png()
      .toBuffer()
    writeFileSync(imagePath, materialBytes)

    return {
      approvedAssetId: `approved-material-${index}`,
      slotId: slot.slotId,
      source:
        slot.painterContract.inputKind === "condition_mask_object"
          ? "ai_painter_object_visual_unit"
          : "ai_painter_region_texture",
      imageUrl: imagePath,
      imageSha256: sha256(materialBytes),
      imageWidth,
      imageHeight,
      imageFormat: "png",
      sourceFactIds: slot.sourceFactIds,
      tags: ["approved_ai_painter_visual_unit_material"],
    }
  })
)

