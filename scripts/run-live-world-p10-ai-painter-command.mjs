import { createHash } from "node:crypto";
import { access, readFile, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";
import path from "node:path";

const root = process.cwd();
const now = "2026-07-06T00:00:00.000Z";
const runId = "p10-ai-painter-command-run-0001";

const dispatchPath = path.join(root, "data/live-world/visual-generation-dispatches/p10-active-chunks/ai-painter-dispatch.json");
const runRecordPath = path.join(root, "data/live-world/visual-generation-dispatches/p10-active-chunks/ai-painter-command-run.json");
const latestPath = path.join(root, "data/live-world/visual-generation-dispatches/latest-ai-painter-command-run.json");

function projectPath(filePath) {
  return path.relative(root, filePath).replaceAll("\\", "/");
}

async function fileExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function sha256File(filePath) {
  const buffer = await readFile(filePath);
  return createHash("sha256").update(buffer).digest("hex");
}

function runCommand(command, env) {
  return new Promise((resolve) => {
    const child = spawn(command, {
      cwd: root,
      shell: true,
      env: {
        ...process.env,
        ...env,
      },
      stdio: ["ignore", "pipe", "pipe"],
    });

    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (chunk) => {
      stdout += chunk.toString();
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk.toString();
    });
    child.on("close", (exitCode) => {
      resolve({ exitCode, stdout, stderr });
    });
    child.on("error", (error) => {
      resolve({ exitCode: -1, stdout, stderr: error.message });
    });
  });
}

async function writeJson(filePath, value) {
  await writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

const dispatch = JSON.parse(await readFile(dispatchPath, "utf8"));
const aiPainterCommand = process.env.LIVE_WORLD_AI_PAINTER_COMMAND?.trim() || null;
const entries = [];

for (const entry of dispatch.entries) {
  const inputPath = path.join(root, entry.candidateInputPath);
  const outputImagePath = path.join(root, entry.expectedOutputImagePath);
  const outputMetaPath = path.join(root, entry.outputMetaPath);
  const candidateMetaPath = path.join(root, entry.candidateMetaPath);

  if (!aiPainterCommand) {
    entries.push({
      candidateId: entry.candidateId,
      chunkId: entry.chunkId,
      inputPath: entry.candidateInputPath,
      outputImagePath: entry.expectedOutputImagePath,
      outputMetaPath: entry.outputMetaPath,
      status: "blocked",
      exitCode: null,
      imageGenerated: false,
      imageHash: null,
      errorMessage: "LIVE_WORLD_AI_PAINTER_COMMAND is not configured.",
    });
    continue;
  }

  const result = await runCommand(aiPainterCommand, {
    LIVE_WORLD_CANDIDATE_ID: entry.candidateId,
    LIVE_WORLD_CHUNK_ID: entry.chunkId,
    LIVE_WORLD_INPUT_PATH: projectPath(inputPath),
    LIVE_WORLD_OUTPUT_IMAGE_PATH: projectPath(outputImagePath),
    LIVE_WORLD_OUTPUT_META_PATH: projectPath(outputMetaPath),
    LIVE_WORLD_CANDIDATE_ROOT: entry.candidateRoot,
  });

  const imageGenerated = result.exitCode === 0 && await fileExists(outputImagePath);
  const imageHash = imageGenerated ? await sha256File(outputImagePath) : null;
  const outputMeta = JSON.parse(await readFile(outputMetaPath, "utf8"));
  const candidateMeta = JSON.parse(await readFile(candidateMetaPath, "utf8"));

  if (imageGenerated) {
    await writeJson(outputMetaPath, {
      ...outputMeta,
      modelVersion: "LIVE_WORLD_AI_PAINTER_COMMAND",
      generatedAt: now,
      status: "generated",
      imageGenerated: true,
      outputImageHash: imageHash,
      reason: "Generated by LIVE_WORLD_AI_PAINTER_COMMAND and ready for automatic structure review.",
    });
    await writeJson(candidateMetaPath, {
      ...candidateMeta,
      status: "pending_structure_review",
      imageGenerated: true,
      outputImageHash: imageHash,
      notes: "P10 candidate image generated and waiting for automatic structure review.",
    });
  }

  entries.push({
    candidateId: entry.candidateId,
    chunkId: entry.chunkId,
    inputPath: entry.candidateInputPath,
    outputImagePath: entry.expectedOutputImagePath,
    outputMetaPath: entry.outputMetaPath,
    status: imageGenerated ? "generated" : "failed",
    exitCode: result.exitCode,
    imageGenerated,
    imageHash,
    errorMessage: imageGenerated
      ? null
      : [
          `AI Painter command failed or did not create output.image.png for ${entry.candidateId}.`,
          result.stderr.trim(),
        ].filter(Boolean).join(" "),
  });
}

const generatedCount = entries.filter((entry) => entry.status === "generated").length;
const failedCount = entries.filter((entry) => entry.status === "failed").length;
const blockedCount = entries.filter((entry) => entry.status === "blocked").length;
const status = blockedCount > 0
  ? "blocked_missing_ai_painter_command"
  : failedCount > 0
    ? "partial_failed"
    : "completed";

const runRecord = {
  runVersion: "live-world-p10-ai-painter-command-run-v1",
  runId,
  dispatchId: dispatch.dispatchId,
  status,
  aiPainterCommand,
  entries,
  generatedCount,
  failedCount,
  blockedCount,
  commandProtocol: {
    inputEnv: [
      "LIVE_WORLD_CANDIDATE_ID",
      "LIVE_WORLD_CHUNK_ID",
      "LIVE_WORLD_INPUT_PATH",
      "LIVE_WORLD_OUTPUT_IMAGE_PATH",
      "LIVE_WORLD_OUTPUT_META_PATH",
      "LIVE_WORLD_CANDIDATE_ROOT",
    ],
    outputFiles: [
      "output.image.png",
      "output.meta.json",
    ],
    successCriteria: [
      "process exit code is 0",
      "output.image.png exists",
      "output image sha256 can be computed",
      "candidate remains outside approved visuals until review passes",
    ],
  },
  forbiddenSideEffects: {
    writesApprovedVisuals: false,
    writesTrainingSamples: false,
    bypassesRuntimePageGate: false,
  },
  createdAt: now,
};

await writeJson(runRecordPath, runRecord);
await writeJson(latestPath, {
  runId,
  dispatchId: dispatch.dispatchId,
  status,
  runRecordPath: projectPath(runRecordPath),
  generatedCount,
  failedCount,
  blockedCount,
  createdAt: now,
});

console.log(`Wrote ${projectPath(runRecordPath)}`);
console.log(`runId=${runId}`);
console.log(`status=${status}`);
console.log(`generatedCount=${generatedCount}`);
console.log(`failedCount=${failedCount}`);
console.log(`blockedCount=${blockedCount}`);
